namespace AGNIDAWN.Gameplay.MetaProgression
{
    /// <summary>
    /// The five divine shrines available for meta-progression.
    /// Each shrine represents a deity and governs a different unlock category.
    /// Linear: FAI-13
    /// </summary>
    public enum ShrineType
    {
        Brahma,      // Unlock new starting weapons
        Vishnu,      // Unlock passive upgrades available during runs
        Shiva,       // Unlock new playable characters
        Saraswati,   // Unlock lore pages and art gallery
        Lakshmi      // Upgrade Divine Shard multiplier (earn more shards per run)
    }
}
